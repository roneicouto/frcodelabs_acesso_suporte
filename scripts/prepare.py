"""Apply the FR CODE LABS overlay to the pinned RustDesk source without resetting files."""
import base64
import hashlib
import json
import os
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "upstream"


def replace_once(path, old, new):
    text = path.read_text(encoding="utf-8")
    if new in text:
        return
    if text.count(old) != 1:
        raise RuntimeError(f"Unexpected upstream content: {path}, matches={text.count(old)}")
    path.write_text(text.replace(old, new, 1), encoding="utf-8", newline="\n")


def write_if_changed(path, text):
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def main():
    config = json.loads((ROOT / "config/client.json").read_text(encoding="utf-8"))
    if (SOURCE / ".git").exists():
        tag = subprocess.check_output(["git", "describe", "--tags", "--exact-match", "HEAD"], cwd=SOURCE, text=True).strip()
    else:
        tag = json.loads((ROOT / "config/source-lock.json").read_text(encoding="utf-8"))["tag"]
    if tag != config["upstream_tag"]:
        raise RuntimeError(f"Expected RustDesk {config['upstream_tag']}, got {tag}")
    key_env = os.environ.get("FR_PUBLIC_KEY", "").strip()
    key = key_env if key_env else (ROOT / config["public_key_file"]).read_text(encoding="utf-8-sig").strip()
    if len(base64.b64decode(key, validate=True)) != 32:
        raise ValueError("Expected a 32-byte Ed25519 public key")
    id_server = os.environ.get("FR_ID_SERVER", "").strip() or config.get("id_server", "").strip()
    relay_server = os.environ.get("FR_RELAY_SERVER", "").strip() or config.get("relay_server", "").strip()
    default_password = os.environ.get("FR_DEFAULT_PASSWORD", "").strip() or config.get("default_receive_password", "").strip()
    secondary_password = os.environ.get("FR_SECONDARY_PASSWORD", "").strip() or config.get("secondary_receive_password", "").strip()
    if not id_server or not relay_server:
        raise ValueError("Missing id_server / relay_server (set FR_ID_SERVER and FR_RELAY_SERVER secrets or config/client.json)")
    if len(default_password) < 12:
        raise ValueError("Receive password must contain at least 12 characters (set FR_DEFAULT_PASSWORD secret or config/client.json)")
    if secondary_password and len(secondary_password) < 12:
        raise ValueError("Secondary receive password must contain at least 12 characters")

    xor_key = hashlib.sha256(f"FRCodeLabs:{key}:{config['version']}".encode("utf-8")).digest()

    def xor_bytes(value: str) -> str:
        raw = value.encode("utf-8")
        enc = [b ^ xor_key[i % len(xor_key)] for i, b in enumerate(raw)]
        return "&[" + ", ".join(str(b) for b in enc) + "]"

    encoded_constants = {
        "ID_SERVER_ENC": xor_bytes(id_server),
        "RELAY_SERVER_ENC": xor_bytes(relay_server),
        "PUBLIC_KEY_ENC": xor_bytes(key),
        "DEFAULT_RECEIVE_PASSWORD_ENC": xor_bytes(default_password),
        "SECONDARY_RECEIVE_PASSWORD_ENC": xor_bytes(secondary_password),
    }
    plain_constants = {
        "FULL_APP_NAME": config["full_app_name"],
        "QS_APP_NAME": config["qs_app_name"],
    }
    xor_key_literal = "&[" + ", ".join(str(b) for b in xor_key) + "]"
    write_if_changed(SOURCE / "src/cf_link_config.rs",
        "// Generated by scripts/prepare.py; values are XOR-obfuscated in the binary.\n"
        f"pub const XOR_KEY: &[u8] = {xor_key_literal};\n" +
        "".join(f"pub const {name}: &[u8] = {val};\n" for name, val in encoded_constants.items()) +
        "".join(f"pub const {name}: &str = {json.dumps(value)};\n" for name, value in plain_constants.items()) +
        "pub fn decode(bytes: &[u8]) -> String {\n"
        "    let out: Vec<u8> = bytes.iter().enumerate().map(|(i, b)| b ^ XOR_KEY[i % XOR_KEY.len()]).collect();\n"
        "    String::from_utf8(out).expect(\"valid utf-8\")\n"
        "}\n",
    )
    write_if_changed(SOURCE / "src/cf_link.rs", (ROOT / "scripts/cf_link.rs").read_text(encoding="utf-8"))
    write_if_changed(SOURCE / "libs/portable/src/cf_installer.rs",
        (ROOT / "scripts/cf_portable_installer.rs").read_text(encoding="utf-8").replace(
            '"__CF_FULL_APP_NAME__"', json.dumps(config["full_app_name"])))
    replace_once(SOURCE / "libs/portable/src/main.rs", "fn main() -> Result<(), String> {",
        '#[cfg(windows)]\nmod cf_installer;\n\nfn main() -> Result<(), String> {')
    replace_once(SOURCE / "libs/portable/src/main.rs", "    let reader = BinaryReader::new()?;",
        '    let reader = BinaryReader::new()?;\n    #[cfg(windows)]\n    let click_setup = click_setup || cf_installer::is_full_installer(&reader.exe, &args);')
    replace_once(SOURCE / "src/client.rs", '        PeerConfig::load(&self.id)', '''        let config = PeerConfig::load(&self.id);
        #[cfg(any(feature = "cf-full", feature = "cf-qs"))]
        let config = crate::cf_link::peer_config(config);
        config''')
    conn_file = SOURCE / "src/server/connection.rs"
    old_single_preset = '''            #[cfg(any(feature = "cf-full", feature = "cf-qs"))]
            if let Some(preset) = crate::cf_link::receive_password() {
                let accepted = self.validate_password_plain(preset);
                if accepted {
                    self.set_conn_audit_primary_auth(ConnAuditPrimaryAuth::PermanentPassword);
                }
                return accepted;
            }'''
